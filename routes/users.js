//Even though we imported Express in index.js, that doesn't automatically make it available inside users.js so we add the below line
const express = require("express");

const User = require("../models/user"); // This imports the user class

//In index.js We used "const app = express();"" to create our main Express application and define APIs.
//Now we're creating a mini application specifically for Users APIs  by the below line
const router = express.Router(); //Creates a mini-router to manage all Users APIs.

const db = require("../db"); //Imports the database connection from db.js (one folder up).

/// GET - ALL USERS
router.get("/", (req, res) => {
  db.query("SELECT * FROM users", (err, result) => {
    if (err) {
      res.send(err.message);
    } else {
      res.json(result);
    }
  });
});

//POST REQUEST - ADDING NEW USER
router.post("/", (req, res) => {
  const data = new User(
    null, //null cuz the db automatically generates user_id using AUTO_INCREMENT.
    req.body.full_name,
    req.body.email,
    req.body.password,
    req.body.phone,
    req.body.role,
  );

  const sql =
    "INSERT INTO users (full_name, email, password, phone, role) VALUES (?, ?, ?, ?, ?)";

  db.query(
    sql,
    [data.full_name, data.email, data.password, data.phone, data.role],
    (err, result) => {
      if (err) {
        res.send(err.message);
      } else {
        data.user_id = result.insertId; //result.insertId gives us the ID generated by the database then We save that ID inside our User object.
        res.json(data.getUserInfo()); //data.getUserInfo() calls the method we created in User.js class
        //res.json() sends the returned user information as JSON.
      }
    },
  );
});
///PUT REQUEST - EDITING SPECIFIC USER INFO/DETAILS
router.put("/:id", (req, res) => {
  const id = req.params.id;
  const phone = req.body.phone;

  const sql = "UPDATE users SET phone = ? WHERE user_id = ?";

  db.query(sql, [phone, id], (err, result) => {
    if (err) {
      res.send(err.message);
    } else {
      res.send("User updated successfully!");
    }
  });
});
////DELETE USER
router.delete("/:id", (req, res) => {
  const sql = "DELETE FROM users WHERE user_id = ?";

  db.query(sql, [req.params.id], (err, result) => {
    if (err) {
      res.send(err.message);
    } else {
      res.send("User deleted successfully!");
    }
  });
});

////SEARCH USER
router.get("/search/:name", (req, res) => {
  const sql = "SELECT * FROM users WHERE full_name LIKE ?";

  db.query(sql, ["%" + req.params.name + "%"], (err, result) => {
    if (err) {
      res.send(err.message);
    } else {
      res.json(result);
    }
  });
});

// POST user login
router.post("/login", (req, res) => {
  const sql =
    "SELECT user_id, full_name, email, phone, role FROM users WHERE email = ? AND password = ?";

  db.query(sql, [req.body.email, req.body.password], (err, result) => {
    if (err) {
      res.status(500).send(err.message);
    } else if (result.length > 0) {
      res.json({
        message: "Login successful!",
        user: result[0],
      });
    } else {
      res.status(401).send("Invalid email or password!");
    }
  });
});

module.exports = router; //Exporting the router so index.js or other files can use it
/////We use POST for login because:
//Login sends sensitive data (email and password) to the server.
// POST sends this data in the request body instead of exposing it in the URL.--> /users/login but body of the request will hold the data
//GET is mainly used to retrieve data, not submit login credentials---> /users/login?email=ahmed@example.com&password=test123
//POST is used to send data to the server to perform an action. It doesn't always mean adding data to the database
